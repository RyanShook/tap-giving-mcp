#!/usr/bin/env python3
"""Emit the Worker's example-asset modules from the rendered set.

Both asset kinds ship as generated TypeScript string modules under
src/example-assets/: <id>.svg.ts exports the SVG source text and
<id>.png.ts exports the standard base64 of the rendered PNG. String
modules are portable in every bundler and in the plain node test
runner, which binary and text imports are not. Run after
assets-src/gen_examples.py.
"""
import base64
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ASSETS = os.path.join(HERE, "..", "src", "example-assets")

def main():
    ids = sorted(f[:-4] for f in os.listdir(ASSETS) if f.endswith(".png"))
    if not ids:
        print("no PNGs found; run assets-src/gen_examples.py first", file=sys.stderr)
        return 1
    for ex_id in ids:
        with open(os.path.join(ASSETS, f"{ex_id}.png"), "rb") as fh:
            b64 = base64.b64encode(fh.read()).decode("ascii")
        with open(os.path.join(ASSETS, f"{ex_id}.png.ts"), "w", encoding="utf-8") as fh:
            fh.write(f'// Generated by tools/build-examples.py from {ex_id}.png; do not edit by hand.\n')
            fh.write(f'export default "{b64}";\n')
        print(f"{ex_id}.png.ts: {len(b64)} base64 chars")
        import json as _json
        with open(os.path.join(ASSETS, f"{ex_id}.svg"), encoding="utf-8") as fh:
            svg_text = fh.read()
        with open(os.path.join(ASSETS, f"{ex_id}.svg.ts"), "w", encoding="utf-8") as fh:
            fh.write(f'// Generated by tools/build-examples.py from {ex_id}.svg; do not edit by hand.\n')
            fh.write(f'export default {_json.dumps(svg_text)};\n')
        print(f"{ex_id}.svg.ts: {len(svg_text)} chars")
    return 0

if __name__ == "__main__":
    sys.exit(main())
