// Build the MCP example and photo assets from the website asset library.
//
// Examples: one latest DELIVERED proof per delivered organization. The
// delivered set and its evidence live in tools/delivered-examples.json
// (built by cross-matching accounting/orders/_manifest.json,
// accounting/orders/_status.json and CRM/deals.csv in the business repo;
// see docs/spec.md landing note of 2026-11-08). Source bytes come only
// from ~/work/tap-giving-worker/website/assets/proofs/.
// Photos: labeled setting / explainer images from
// ~/work/tap-giving-worker/website/assets/ (outside proofs/), listed in
// tools/photos.json with honest labels per documentation/visual-assets.md.
//
// Output: build/kv-bulk.json for `wrangler kv bulk put` into the
// MCP_ARTWORK namespace (keys EXAMPLE:<id> and PHOTO:<id>), plus the
// committed metadata indexes src/examples-data.ts and src/photos-data.ts.
// Image bytes never enter the Worker bundle.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const repo = join(dirname(fileURLToPath(import.meta.url)), "..");
const ASSETS = process.env.TG_ASSETS || "/home/ubuntu/work/tap-giving-worker/website/assets";
const PROOFS = join(ASSETS, "proofs");

const examples = JSON.parse(readFileSync(join(repo, "tools/delivered-examples.json"), "utf8"));
const photos = JSON.parse(readFileSync(join(repo, "tools/photos.json"), "utf8"));

async function classifyShape(buf) {
  // Deterministic shape test at native resolution. (A resize-to-100px
  // corner sample proved unstable across processes for palette PNGs:
  // antialiased disc edges bled into the corner patches.)
  // Alpha proofs: a round disc never reaches its canvas corners
  // (corner alpha ~0); a square disc fills them (~240, rounded corners
  // aside). No-alpha proofs (rendered on a solid background): a round
  // disc inscribed in the canvas is narrow near the top and bottom
  // edges, a square disc spans nearly full width at every height.
  const meta = await sharp(buf).metadata();
  const W = meta.width, H = meta.height, s = Math.max(8, Math.floor(Math.min(W, H) * 0.06));
  if (meta.hasAlpha) {
    let total = 0;
    for (const [left, top] of [[0, 0], [W - s, 0], [0, H - s], [W - s, H - s]]) {
      const { data, info } = await sharp(buf).extract({ left, top, width: s, height: s }).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
      let a = 0; for (let i = 3; i < data.length; i += info.channels) a += data[i];
      total += a / (s * s);
    }
    return (total / 4) > 25 ? "square" : "round";
  }
  const { data, info } = await sharp(buf).resize(200, 200, { fit: "fill" }).raw().toBuffer({ resolveWithObject: true });
  const ch = info.channels, bg = [data[0], data[1], data[2]];
  const widthAt = (y) => { let first = -1, last = -1; for (let x = 0; x < 200; x++) { const i = (y * 200 + x) * ch; const d = Math.abs(data[i] - bg[0]) + Math.abs(data[i + 1] - bg[1]) + Math.abs(data[i + 2] - bg[2]); if (d > 30) { if (first < 0) first = x; last = x; } } return first < 0 ? 0 : last - first + 1; };
  const mid = widthAt(100), top = widthAt(14), bot = widthAt(186);
  return (top < mid * 0.85 || bot < mid * 0.85) ? "round" : "square";
}

const bulk = [];
const exampleIndex = [];
let exampleBytes = 0;
for (const ex of examples) {
  const src = readFileSync(join(PROOFS, ex.source));
  const png = await sharp(src, { density: 300 })
    .resize(424, 424, { fit: "inside" })
    .png({ compressionLevel: 9, effort: 10 })
    .toBuffer();
  const shape = ex.source.endsWith(".svg") ? await classifyShape(png) : await classifyShape(src);
  bulk.push({ key: `EXAMPLE:${ex.id}`, value: png.toString("base64"), base64: true });
  exampleIndex.push({ id: ex.id, organization: ex.organization, shape, stage: ex.stage, source: ex.source, description: ex.description, size: ex.size, palette: ex.palette, layout: ex.layout, iconTreatment: ex.iconTreatment, logoSlot: ex.logoSlot });
  exampleBytes += png.length;
  console.log(`example ${ex.id}: ${shape}, ${png.length} bytes, from ${ex.source}`);
}

const photoIndex = [];
let photoBytes = 0;
for (const ph of photos) {
  const srcPath = ph.source.startsWith("repo:") ? join(repo, ph.source.slice(5)) : join(ASSETS, ph.source);
  const webp = await sharp(readFileSync(srcPath))
    .resize(1000, 1000, { fit: "inside", withoutEnlargement: true })
    .webp({ quality: 80 })
    .toBuffer();
  bulk.push({ key: `PHOTO:${ph.id}`, value: webp.toString("base64"), base64: true });
  photoIndex.push({ id: ph.id, category: ph.category, title: ph.title, alt: ph.alt, use: ph.use, source: ph.source });
  photoBytes += webp.length;
  console.log(`photo ${ph.id}: ${webp.length} bytes, from ${ph.source}`);
}

mkdirSync(join(repo, "build"), { recursive: true });
writeFileSync(join(repo, "build/kv-bulk.json"), JSON.stringify(bulk));
writeFileSync(join(repo, "src/examples-data.ts"),
  "// Generated by tools/build-assets.mjs from tools/delivered-examples.json.\n" +
  "// Metadata only: image bytes live in the MCP_ARTWORK KV namespace under\n" +
  "// EXAMPLE:<id> and derive solely from delivered proof files in the\n" +
  "// website asset library (website/assets/proofs/). Do not edit by hand.\n" +
  "export interface ExampleLogoSlot { position: string; maxWidthMm: number; maxHeightMm: number; clearSpaceMm: number; note: string }\n" +
  "export interface DeliveredExample { id: string; organization: string; shape: \"round\" | \"square\"; stage: string; source: string; description: string; size: string; palette: { hex: string; role: string }[]; layout: string; iconTreatment: string; logoSlot: ExampleLogoSlot }\n" +
  `export const EXAMPLES_INDEX: DeliveredExample[] = ${JSON.stringify(exampleIndex, null, 2)};\n`);
writeFileSync(join(repo, "src/photos-data.ts"),
  "// Generated by tools/build-assets.mjs from tools/photos.json.\n" +
  "// Metadata only: image bytes live in the MCP_ARTWORK KV namespace under\n" +
  "// PHOTO:<id> and derive solely from website/assets/ files. Labels follow\n" +
  "// the honesty rules in the business repo documentation/visual-assets.md.\n" +
  "// Do not edit by hand.\n" +
  "export interface LabeledPhoto { id: string; category: string; title: string; alt: string; use: string; source: string }\n" +
  `export const PHOTOS_INDEX: LabeledPhoto[] = ${JSON.stringify(photoIndex, null, 2)};\n`);
console.log(`\n${exampleIndex.length} examples (${exampleBytes} bytes total), ${photoIndex.length} photos (${photoBytes} bytes total)`);
console.log("wrote build/kv-bulk.json, src/examples-data.ts, src/photos-data.ts");
